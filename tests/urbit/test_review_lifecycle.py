from digests import sha, tree_sha


class ReviewLifecycleTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='stead-review-test-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.state = self.root / '.piers/review'
        self.backups = self.root / '.piers/review-backups'
        self.adoption = self.backups / 'preview-20261108/current'
        self.stack = ExitStack()
        self.addCleanup(self.stack.close)
        for module, values in ((review, {'ROOT': self.root, 'STATE': self.state, 'BACKUPS': self.backups, 'ADOPTION': self.adoption}),
                               (harness, {'ROOT': self.root, 'BASE': self.root / '.piers', 'STATE': self.root / '.piers/fakes',
                                          'IDENTITY': {'format': 1, 'purpose': 'stead-urbit-four-fakes', 'ships': list(harness.SHIPS)}, 'REVIEW': False})):
            for name, value in values.items():
                self.stack.enter_context(patch.object(module, name, value))
        self.lock = self.root / 'toolchain.json'
        self.lock.write_text('{"synthetic":true}')
        self.stack.enter_context(patch.object(toolchain, 'LOCK_PATH', self.lock))
        self.native = self.root / 'native/core/desk'
        (self.native / 'app').mkdir(parents=True)
        (self.native / 'app/stead-home.hoon').write_text('synthetic native state contract')
        self.old_assets(self.native)

    def old_assets(self, base):
        folder = base / 'web/stead'
        folder.mkdir(parents=True, exist_ok=True)
        import hashlib
        body = b'synthetic prior frontend'
        digest = hashlib.sha256(body).hexdigest()
        (folder / ('asset-' + digest + '.stead-asset')).write_bytes(body)
        (folder / 'inventory.hoon').write_text('::  Generated by web/app/package-desk.mjs from verified manifest bytes.\n'
                                             "'asset-" + digest + "'\n")
        return {'format': 1, 'classification': 'frontend-build-only',
                'files': {'index.html': {'bytes': len(body), 'sha256': digest}}}

    def fixture(self, target):
        target.mkdir(parents=True, mode=0o700)
        # mkdir(parents) obeys the host umask, so explicitly protect ancestors.
        for path in (self.root / '.piers', self.backups, target.parent, target):
            if path.exists():
                path.chmod(0o700)
        execution_policy.write_json(target / harness.MARKER,
            {'format': 1, 'purpose': 'stead-urbit-four-fakes', 'ships': list(harness.SHIPS)})
        manifest = {'format': 1, 'toolchain_sha256': sha(self.lock), 'ships': {}}
        (target / 'seed').mkdir(mode=0o700)
        for ship in harness.SHIPS:
            (target / 'seed' / ship / '.urb').mkdir(parents=True)
            (target / 'seed' / ship / '.urb/seed').write_text(ship)
            manifest['ships'][ship] = tree_sha(target / 'seed' / ship)
            (target / 'live' / ship / '.urb').mkdir(parents=True)
            (target / 'live' / ship / '.urb/accepted-state').write_text('saved user text ' + ship)
            shutil.copytree(self.native, target / 'live' / ship / 'base')
        execution_policy.write_json(target / 'seed/manifest.json', manifest)

    def adoption_fixture(self):
        self.fixture(self.adoption)
        source = self.adoption.parent / 'source'
        source.mkdir(mode=0o700)
        execution_policy.write_json(source / 'source-context.json',
            {'source_commit': 'a' * 40, 'native_tree_sha256': tree_sha(self.native)})
        execution_policy.write_json(source / 'frontend-manifest.json', self.old_assets(self.native))
        execution_policy.write_json(source / 'guard-report.json',
            {'run_id': 'a' * 32, 'status': 'failed', 'exit_code': 1, 'reason': 'Thermal ceiling reached'})
        certificates = self.adoption / 'ingress' / ('a' * 32) / 'certificates'
        certificates.mkdir(parents=True, mode=0o700)
        (certificates / 'synthetic-ca').write_text('private synthetic fixture')

    def own_review(self):
        self.fixture(self.state)
        execution_policy.write_json(self.state / harness.MARKER,
            {'format': 1, 'purpose': 'stead-urbit-manual-review', 'ships': list(harness.SHIPS)})
        data = review.base_metadata('resume')
        data['stopped_piers'] = review.pier_hashes(self.state)
        execution_policy.write_json(self.state / 'review.json', data)
        return data

    def test_adoption_preserves_accepted_state_and_source(self):
        self.adoption_fixture()
        before = review.pier_hashes(self.adoption)
        with patch.object(review, 'require_retired_scope'), redirect_stdout(io.StringIO()):
            review.adopt()
        self.assertEqual(review.pier_hashes(self.state), before)
        self.assertEqual(review.pier_hashes(self.adoption), before)
        data = review.metadata()
        self.assertFalse(data['authority_renewed'])
        self.assertEqual(data['mode'], 'resume')
        self.assertEqual(data['interrupted_source'], 'Thermal ceiling reached')

    def test_active_original_scope_cannot_publish_a_copy(self):
        self.adoption_fixture()
        with patch.object(review, 'require_retired_scope', side_effect=ValueError('still live')):
            with self.assertRaises(ValueError):
                review.adopt()
        self.assertFalse(self.state.exists())

    def test_changed_native_state_contract_rejects_adoption(self):
        self.adoption_fixture()
        (self.adoption / 'live/zod/base/app/stead-home.hoon').write_text('changed code')
        with self.assertRaises(ValueError):
            review.adopt()
        self.assertFalse(self.state.exists())

    def test_prior_asset_tampering_rejects_adoption(self):
        self.adoption_fixture()
        asset = next((self.adoption / 'live/zod/base/web/stead').glob('asset-*'))
        asset.write_bytes(b'different bytes')
        with self.assertRaises(ValueError):
            review.adopt()
        self.assertFalse(self.state.exists())

    def test_failed_copy_remains_archived_and_does_not_claim_ready(self):
        self.adoption_fixture()
        with patch.object(review, 'require_retired_scope'), patch.object(shutil, 'copytree', side_effect=OSError('disk full')):
            with self.assertRaises(OSError):
                review.adopt()
        self.assertFalse(self.state.exists())
        self.assertEqual(len(list(self.backups.glob('review-preparing-*'))), 1)
        self.assertTrue((self.adoption / 'live/zod/.urb/accepted-state').is_file())

    def test_live_lock_rejects_adoption(self):
        self.adoption_fixture()
        with execution_policy.HeavyRunLock(self.adoption / 'lifecycle.lock'):
            with self.assertRaises(BlockingIOError):
                review.adopt()
        self.assertFalse(self.state.exists())

    def test_resume_preserves_saved_bytes_and_prior_recovery_fingerprint(self):
        original = self.own_review()
        (self.state / 'live/zod/.urb/accepted-state').write_text('a later accepted edit')
        before = review.pier_hashes(self.state)
        with patch.object(review, 'service_active', return_value=False), patch.object(harness, 'running', return_value=None), \
             patch.object(toolchain, 'verify'), patch.object(execution_policy, 'sample_temperatures'), \
             patch.object(execution_policy, 'validate_sample'), patch.object(harness, 'execution_limits'), \
             patch.object(review, 'service') as service, redirect_stdout(io.StringIO()):
            review.start(resume=True)
        self.assertEqual(review.pier_hashes(self.state), before)
        record = execution_policy.read_json(next((self.state / 'recovery').iterdir()))
        self.assertEqual(record['prior_stopped_piers'], original['stopped_piers'])
        self.assertEqual(record['observed_stopped_piers'], before)
        self.assertEqual(service.call_count, 2)
        self.assertFalse(any('browser' in call.args[0] for call in service.call_args_list))

    def test_stale_relay_refuses_resume_before_runtime_launch(self):
        self.own_review()
        with patch.object(review, 'service_active', side_effect=lambda name: '-relay-' in name), \
             patch.object(review, 'service') as service:
            with self.assertRaisesRegex(ValueError, 'prior relay'):
                review.start(resume=True)
        service.assert_not_called()
        self.assertFalse((self.state / 'recovery').exists())

    def test_existing_browser_is_never_replaced_when_runtime_is_down(self):
        self.own_review()
        with patch.object(review, 'service_active', return_value=True), patch.object(review, 'service') as service, \
             redirect_stdout(io.StringIO()):
            review.open_browser(session_root=self.state)
        service.assert_not_called()

    def test_stop_targets_native_owner_only(self):
        self.own_review()
        with patch.object(harness, 'stop') as stop, patch.object(review, 'service') as service, redirect_stdout(io.StringIO()):
            review.stop()
        stop.assert_called_once_with()
        service.assert_not_called()

    def test_reset_requires_closed_browser_and_exact_session_then_archives(self):
        data = self.own_review()
        with self.assertRaises(ValueError):
            review.reset('wrong-session')
        with patch.object(review, 'service_active', side_effect=lambda name: '-browser-' in name):
            with self.assertRaises(ValueError):
                review.reset(data['session_id'])
        before = review.pier_hashes(self.state)
        with patch.object(review, 'service_active', return_value=False), redirect_stdout(io.StringIO()):
            review.reset(data['session_id'])
        self.assertFalse(self.state.exists())
        self.assertEqual(review.pier_hashes(self.backups / ('review-' + data['session_id'])), before)

    def test_only_generated_asset_inventory_is_exempt_from_native_contract(self):
        before = review_prepare.hoon_inventory(self.native)
        (self.native / 'web/stead/inventory.hoon').write_text('new asset inventory')
        self.assertEqual(review_prepare.hoon_inventory(self.native), before)
        (self.native / 'web/stead/other.hoon').write_text('executable Hoon')
        self.assertNotEqual(review_prepare.hoon_inventory(self.native), before)

    def test_manual_service_has_no_test_pipe_or_runtime_deadline(self):
        with patch.object(review, 'service_active', return_value=False), patch.object(review.subprocess, 'run') as run:
            review.service('stead-review-browser-' + 'b' * 32 + '.service', ['/usr/bin/true'], environment={'LANG': 'C.UTF-8'}, cpu='25%')
        arguments = run.call_args.args[0]
        self.assertIn('--property=CPUQuota=25%', arguments)
        self.assertIn('--property=KillMode=control-group', arguments)
        self.assertFalse(any('RuntimeMax' in arg for arg in arguments))
        self.assertNotIn('--pipe', arguments)
        self.assertNotIn('--wait', arguments)
        self.assertIn('-i', arguments)

    def resume_host(self):
        self.own_review()
        directory = self.state / 'ingress' / ('c' * 32)
        directory.mkdir(parents=True)
        events = []
        team = SimpleNamespace(directory=directory, certificates=directory / 'certificates',
                               reinstall=lambda ship, dojo: events.append(('reload', ship)),
                               admit=lambda ship, ack, dojo: events.append(('admit', ship)))
        host = {'STATE': self.state, 'LIVE': self.state / 'live', 'SHIPS': harness.SHIPS,
                'TEAM': team, 'PROGRESS': {}, 'LOCK': {'runtime': {'binary': 'bin/synthetic'}},
                'execution_check': lambda **kwargs: {'run_id': 'c' * 32},
                'launch': lambda ship, **kwargs: events.append(('launch', ship)),
                'wait_ready': lambda ship: events.append(('suspended', ship)),
                'dojo': lambda ship, source: 'synthetic-private-code',
                'record': lambda name, evidence: events.append(('record', name)),
                'copy_seed_to_live': Mock(side_effect=AssertionError('Resume must never reseed'))}
        return host, events

    def test_resume_rebuilds_projection_but_checks_all_durable_state_before_release(self):
        host, events = self.resume_host()
        expected = {ship: str(index) * 64 for index, ship in enumerate(harness.SHIPS, 1)}
        calls = []
        def fingerprint(ship, dojo):
            calls.append(ship)
            events.append(('durable', ship))
            return expected[ship]
        def imported(host, ship, command, require):
            # Mock Clay's real observed behavior: the idle app revives and its
            # derived projection differs. Durable business state is unchanged.
            events.append(('clay-revived-with-new-projection', ship))
        with patch.object(review_prepare, 'hoon_inventory', return_value=review.hoon_inventory(self.native)), \
             patch.object(review_prepare, 'sha', return_value=sha(self.lock)), \
             patch.object(review_prepare, 'durable_fingerprint', side_effect=fingerprint), \
             patch.object(review_prepare.native_install, 'install', side_effect=imported), \
             patch.object(review_prepare.team_check, 'bootstrap_ready', side_effect=lambda team, ship, call, guard: events.append(('restored', ship)) or {'ready': ship}), \
             patch.object(review_prepare.native_tls, 'install', side_effect=lambda binary, channel, directory, ship: events.append(('tls', ship))):
            review_prepare.run(host)
        self.assertEqual(calls, list(harness.SHIPS) * 2)
        self.assertGreater(next(i for i, event in enumerate(events) if event[0] == 'tls'),
                           max(i for i, event in enumerate(events) if event[0] == 'durable'))
        self.assertGreater(next(i for i, event in enumerate(events) if event[0] == 'admit'),
                           max(i for i, event in enumerate(events) if event[0] == 'tls'))
        self.assertEqual([ship for name, ship in events if name == 'admit'], list(harness.SHIPS))
        host['copy_seed_to_live'].assert_not_called()

    def test_changed_durable_state_fails_before_any_tls_or_peer_release(self):
        host, events = self.resume_host()
        count = {}
        def fingerprint(ship, dojo):
            count[ship] = count.get(ship, 0) + 1
            return ('b' if ship == 'bus' and count[ship] > 1 else 'a') * 64
        with patch.object(review_prepare, 'hoon_inventory', return_value=review.hoon_inventory(self.native)), \
             patch.object(review_prepare, 'sha', return_value=sha(self.lock)), \
             patch.object(review_prepare, 'durable_fingerprint', side_effect=fingerprint), \
             patch.object(review_prepare.native_install, 'install'), \
             patch.object(review_prepare.team_check, 'bootstrap_ready', return_value={'ready': True}), \
             patch.object(review_prepare.native_tls, 'install') as tls:
            with self.assertRaisesRegex(ValueError, 'bus durable state unchanged'):
                review_prepare.run(host)
        tls.assert_not_called()
        self.assertFalse(any(name == 'admit' for name, _ in events))
        host['copy_seed_to_live'].assert_not_called()

    def test_durable_fingerprint_rejects_invalid_native_output(self):
        for value in ('not-a-hash', '0x' + 'f' * 65):
            with self.subTest(value=value), self.assertRaises(ValueError):
                review_prepare.durable_fingerprint('zod', Mock(side_effect=['%base', value]))
        with self.assertRaisesRegex(ValueError, 'verified desk'):
            review_prepare.durable_fingerprint('bus', Mock(return_value='%other'))


