"""Host-only manual-review lifecycle checks. No Urbit or browser is launched.

Filesystem copying/hashing/locking is real in private temporary directories;
systemd, native execution and admission responses are explicitly mocked.
"""
from contextlib import ExitStack, redirect_stdout
