#!/usr/bin/env python3
"""Reproducible offline desk candidate; never installs, migrates or publishes.

Repository inputs come from one Git commit. Dependencies must match the checked
release contract. Verification needs an externally trusted archive digest and
an explicit target profile; it never extracts or executes archive contents.
"""
from __future__ import annotations
import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tarfile

from package_sdk import ROOT, encoded, held_parent, read_bounded, require, unique

MAX_FILE = 1024 * 1024
MAX_ARCHIVE = 8 * 1024 * 1024
MAX_MEMBERS = 128
PREFIX = 'stead-release/'
CONTRACT = 'specs/urbit/release-package.json'
NATIVE = 'native/core/desk/'
TARGET_KEYS = {'protocol', 'role', 'kernel_kelvin', 'kernel_commit', 'runtime_version',
               'runtime_binary_sha256', 'api_version', 'saved_state_version', 'frontend_sha256'}
INVENTORY_HEAD = ('::  Generated by web/app/package-desk.mjs from verified manifest bytes.\n'
                  '|%\n+$  asset  [file=path mime=@t digest=@t]\n++  inventory\n'
                  '  ^-  (map @t asset)\n  %-  malt\n  :~\n')
INVENTORY_TAIL = ('\n  ==\n++  paths\n  ^-  (set @t)\n'
                  '  (silt (turn ~(tap by inventory) |=([route=@t value=asset] route)))\n--\n')
ROW = re.compile(r"      \['(?P<route>/(?:stead|stead-identity)/(?:assets/[A-Za-z0-9.-]+)?)' "
                 r"\[\[%web %stead 'asset-(?P<digest>[0-9a-f]{64})' %stead-asset ~\] "
                 r"'(?P<mime>text/(?:plain|html|css|javascript); charset=utf-8)' '(?P=digest)'\]\]")


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def git(root, *args):
    # Read real object identities. Caller GIT_DIR/alternate object stores,
    # replacement refs, lazy promisor fetches and user config cannot reinterpret
    # a recorded commit or turn an offline package build into network activity.
    environment = {'PATH': '/usr/bin:/bin', 'LANG': 'C.UTF-8',
                   'GIT_NO_REPLACE_OBJECTS': '1', 'GIT_NO_LAZY_FETCH': '1',
                   'GIT_ALLOW_PROTOCOL': '', 'GIT_TERMINAL_PROMPT': '0',
                   'GIT_CONFIG_NOSYSTEM': '1', 'GIT_CONFIG_GLOBAL': '/dev/null',
                   'GIT_CONFIG_SYSTEM': '/dev/null', 'GIT_ATTR_NOSYSTEM': '1'}
    return subprocess.run(['/usr/bin/git', '-C', str(root), *args], env=environment,
                          check=True, capture_output=True, timeout=20).stdout


def committed(root, commit, name):
    require(re.fullmatch(r'[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)*', name) and '..' not in name.split('/'), 'Unsafe source path')
    rows = git(root, 'ls-tree', '-z', commit, '--', name).split(b'\0')
    require(len(rows) == 2 and not rows[1], 'Committed release input missing: ' + name)
    metadata, found = rows[0].split(b'\t', 1)
    mode, kind, oid = metadata.decode().split()
    require(found.decode() == name and mode in ('100644', '100755') and kind == 'blob', 'Release input must be a committed regular blob')
    size = int(git(root, 'cat-file', '-s', oid))
    require(0 < size <= MAX_FILE, 'Release input byte bound')
    raw = git(root, 'cat-file', 'blob', oid)
    require(len(raw) == size, 'Git blob changed during readback')
    return raw


def source_identity(root, reference):
    require(reference == 'HEAD' or re.fullmatch(r'[0-9a-f]{40}', reference), 'Use HEAD or an exact source commit')
    commit = git(root, 'rev-parse', '--verify', reference + '^{commit}').decode().strip()
    require(re.fullmatch(r'[0-9a-f]{40}', commit), 'Source commit identity')
    return commit


def validate_contract(value):
    require(isinstance(value, dict) and set(value) == {'protocol', 'classification', 'kernel_kelvin', 'kernel_commit', 'runtime_version',
                          'runtime_binary_sha256', 'toolchain_sha256', 'api_version', 'saved_state_versions',
                          'agents', 'marks', 'kernel_files'}, 'Release contract shape')
    require(value['protocol'] == 'stead.release-contract/1' and value['classification'] == 'candidate-packaging-only', 'Release contract version')
    require(type(value['kernel_kelvin']) is int and value['kernel_kelvin'] == 408
            and type(value['api_version']) is int and value['api_version'] == 3
            and value['runtime_version'] == '4.6', 'Unsupported release compatibility')
    require(value['agents'] == {'home': 'stead-home', 'identity': 'stead-identity'}
            and value['saved_state_versions'] == {'home': 3, 'identity': 1}
            and all(type(x) is int for x in value['saved_state_versions'].values()), 'Unsupported app/state profile')
    for name in ('runtime_binary_sha256', 'toolchain_sha256'):
        require(isinstance(value[name], str) and re.fullmatch(r'[0-9a-f]{64}', value[name]), 'Invalid release hash')
    require(re.fullmatch(r'[0-9a-f]{40}', value['kernel_commit']), 'Invalid kernel commit')
    require(isinstance(value['marks'], list) and value['marks'] == sorted(set(value['marks'])) and 0 < len(value['marks']) <= 32
            and all(re.fullmatch(r'stead-[a-z0-9-]+', name) for name in value['marks']), 'Release mark inventory')
    require(isinstance(value['kernel_files'], dict) and 0 < len(value['kernel_files']) <= 32, 'Kernel dependency inventory')
    for name, pin in value['kernel_files'].items():
        require(name == 'LICENSE.txt' or re.fullmatch(r'(?:lib|mar|sur)/[a-z0-9-]+\.hoon', name), 'Kernel dependency path')
        validate_pin(pin)
    require('LICENSE.txt' in value['kernel_files'], 'Pinned kernel license is required')
    require({'mar/hoon.hoon', 'mar/noun.hoon', 'mar/txt.hoon', 'mar/kelvin.hoon', 'mar/bill.hoon', 'mar/mime.hoon', 'mar/json.hoon'}
            <= set(value['kernel_files']), 'Self-contained standard marks are required')


def validate_pin(pin):
    require(isinstance(pin, dict) and set(pin) == {'bytes', 'sha256'}
            and type(pin['bytes']) is int and 0 < pin['bytes'] <= MAX_FILE
            and isinstance(pin['sha256'], str) and re.fullmatch(r'[0-9a-f]{64}', pin['sha256']), 'Invalid file pin')


def frontend(reader):
    raw = reader('web/stead/inventory.hoon')
    text = raw.decode('utf-8')
    require(text.startswith(INVENTORY_HEAD) and text.endswith(INVENTORY_TAIL), 'Generated frontend inventory differs')
    lines = text[len(INVENTORY_HEAD):-len(INVENTORY_TAIL)].splitlines()
    require(0 < len(lines) <= 32, 'Frontend route bound')
    routes, members, seen = [], {'web/stead/inventory.hoon': raw}, set()
    for line in lines:
        found = ROW.fullmatch(line)
        require(found is not None, 'Unsupported frontend inventory row')
        row = found.groupdict()
        require(row['route'] not in seen and '..' not in row['route'], 'Duplicate or unsafe frontend route')
        seen.add(row['route'])
        name = 'web/stead/asset-' + row['digest'] + '.stead-asset'
        body = reader(name)
        require(0 < len(body) <= 524288 and digest(body) == row['digest'], 'Frontend asset digest differs')
        members[name] = body
        routes.append({'route': row['route'], 'mime': row['mime'], 'sha256': row['digest'], 'bytes': len(body)})
    require('/stead/' in seen and '/stead-identity/' in seen, 'Both native frontend entrypoints are required')
    record = {'protocol': 'stead.release-frontend/1', 'inventory_sha256': digest(raw), 'routes': routes}
    return members, encoded(record)


def imports(raw):
    dependencies = []
    for line in raw.decode('utf-8').splitlines():
        if line.startswith(('/+', '/-')):
            kind = 'lib' if line[:2] == '/+' else 'sur'
            names = [name.strip() for name in line[2:].split(',')]
            require(all(re.fullmatch(r'[a-z][a-z0-9-]*', name) for name in names), 'Unpinned Ford import syntax')
            dependencies.extend(kind + '/' + name + '.hoon' for name in names)
        elif line.startswith('/='):
            found = re.fullmatch(r'/=\s+[a-z][a-z0-9-]*\s+/(lib|sur|web)/([a-z0-9/-]+)', line)
            require(found is not None and '..' not in line, 'Unpinned Ford file import')
            dependencies.append(found[1] + '/' + found[2] + '.hoon')
        elif line.startswith(('/%', '/*')):
            raise ValueError('External or dynamic Ford dependency is not packaged')
    return dependencies


def canonical_archive(members):
    require(0 < len(members) <= MAX_MEMBERS, 'Release member bound')
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode='w', format=tarfile.USTAR_FORMAT) as archive:
        for name, raw in sorted(members.items()):
            require(0 < len(raw) <= MAX_FILE, 'Release member size bound')
            item = tarfile.TarInfo(PREFIX + name)
            item.size, item.mode, item.mtime = len(raw), 0o644, 0
            item.uid = item.gid = 0
            item.uname = item.gname = ''
            archive.addfile(item, io.BytesIO(raw))
    raw = buffer.getvalue()
    require(len(raw) <= MAX_ARCHIVE, 'Release archive bound')
    return raw


def archive_bytes(root=ROOT, *, role, reference='HEAD'):
    require(role in ('home', 'identity'), 'Choose one release role')
    commit = source_identity(root, reference)
    read = lambda name: committed(root, commit, name)
    for name in ('scripts/package_release.py', 'scripts/package_sdk.py'):
        require(read(name) == Path(__file__).with_name(Path(name).name).read_bytes(), 'Run the packager from the selected committed source')
    contract_raw = read(CONTRACT)
    contract = json.loads(contract_raw, object_pairs_hook=unique)
    validate_contract(contract)
    lock_raw = read('specs/urbit/toolchain.lock.json')
    require(digest(lock_raw) == contract['toolchain_sha256'], 'Release toolchain pin differs')
    lock = json.loads(lock_raw, object_pairs_hook=unique)
    require(lock['kernel']['kelvin'] == contract['kernel_kelvin'] and lock['kernel']['commit'] == contract['kernel_commit']
            and lock['runtime']['version'] == contract['runtime_version']
            and lock['runtime']['binary_sha256'] == contract['runtime_binary_sha256'], 'Release runtime/kernel pin differs')
    kernel = '.runtime/' + lock['kernel']['directory'] + '/pkg/arvo/'
    dependencies = {}
    for name, pin in contract['kernel_files'].items():
        body = read_bounded(root, kernel + name, MAX_FILE)
        require(len(body) == pin['bytes'] and digest(body) == pin['sha256'], 'Pinned kernel dependency differs: ' + name)
        dependencies[name] = body
    desk, frontend_raw = frontend(lambda name: read(NATIVE + name))
    pending = ['app/' + contract['agents'][role] + '.hoon'] + ['mar/' + name + '.hoon' for name in contract['marks']]
    pending += [name for name in dependencies if name.startswith('mar/')]
    origins = {name: 'repository:' + NATIVE + name for name in desk}
    while pending:
        name = pending.pop()
        if name in desk:
            continue
        if name in dependencies:
            body, origin = dependencies[name], 'kernel:pkg/arvo/' + name
        else:
            body, origin = read(NATIVE + name), 'repository:' + NATIVE + name
        desk[name], origins[name] = body, origin
        pending.extend(imports(body))
        require(len(desk) <= 100, 'Desk dependency closure bound')
    desk['sys.kelvin'] = f"[%zuse {contract['kernel_kelvin']}]\n".encode()
    desk['desk.bill'] = f":~  %{contract['agents'][role]}\n==\n".encode()
    origins.update({'sys.kelvin': 'generated:kernel-compatibility', 'desk.bill': 'generated:role-agents'})
    members = {'desk/' + name: body for name, body in desk.items()}
    members.update({'LICENSE': read('LICENSE'), 'THIRD_PARTY_NOTICES.md': read('THIRD_PARTY_NOTICES.md'),
                    'notices/urbit-kernel-LICENSE.txt': dependencies['LICENSE.txt'],
                    'OPERATOR.md': read('docs/urbit/RELEASE_PACKAGING.md'),
                    'source/release-contract.json': contract_raw, 'source/toolchain.lock.json': lock_raw,
                    'source/frontend.json': frontend_raw})
    manifest = {'protocol': 'stead.release-package/1', 'kind': 'offline-desk-candidate', 'role': role,
                'source_commit': commit, 'packager_sha256': digest(read('scripts/package_release.py')),
                'shared_packager_sha256': digest(read('scripts/package_sdk.py')),
                'contract_sha256': digest(contract_raw), 'toolchain_sha256': digest(lock_raw),
                'frontend_sha256': digest(frontend_raw),
                'compatibility': {key: contract[key] for key in ('kernel_kelvin', 'kernel_commit', 'runtime_version', 'runtime_binary_sha256', 'api_version')},
                'saved_state_version': contract['saved_state_versions'][role],
                'agents': [contract['agents'][role]], 'docket': 'not-included-native-route-candidate',
                'qualification': {'package_integrity_only': True, 'native_install': False,
                                  'upgrade_recovery': False, 'canary': False, 'production': False},
                'files': {name: {'bytes': len(body), 'sha256': digest(body)} for name, body in sorted(members.items())},
                'desk_sources': {name: origins[name] for name in sorted(origins)}}
    members['manifest.json'] = encoded(manifest)
    return canonical_archive(members), manifest


def target_profile(manifest):
    return {'protocol': 'stead.release-target/1', 'role': manifest['role'], **manifest['compatibility'],
            'saved_state_version': manifest['saved_state_version'], 'frontend_sha256': manifest['frontend_sha256']}


def verify_closure(members, manifest, contract):
    assets, frontend_raw = frontend(lambda name: members['desk/' + name])
    expected = set(assets)
    origins = {name: 'repository:' + NATIVE + name for name in assets}
    pending = ['app/' + contract['agents'][manifest['role']] + '.hoon']
    pending += ['mar/' + name + '.hoon' for name in contract['marks']]
    pending += [name for name in contract['kernel_files'] if name.startswith('mar/')]
    while pending:
        name = pending.pop()
        if name in expected:
            continue
        require('desk/' + name in members, 'Desk dependency is missing: ' + name)
        body = members['desk/' + name]
        if name in contract['kernel_files']:
            pin = contract['kernel_files'][name]
            require(len(body) == pin['bytes'] and digest(body) == pin['sha256'], 'Packaged kernel dependency differs')
            origins[name] = 'kernel:pkg/arvo/' + name
        else:
            origins[name] = 'repository:' + NATIVE + name
        expected.add(name)
        pending.extend(imports(body))
        require(len(expected) <= 100, 'Packaged dependency closure bound')
    expected.update(('sys.kelvin', 'desk.bill'))
    origins.update({'sys.kelvin': 'generated:kernel-compatibility', 'desk.bill': 'generated:role-agents'})
    fixed = {'manifest.json', 'LICENSE', 'THIRD_PARTY_NOTICES.md', 'notices/urbit-kernel-LICENSE.txt',
             'OPERATOR.md', 'source/release-contract.json', 'source/toolchain.lock.json', 'source/frontend.json'}
    require(set(members) == fixed | {'desk/' + name for name in expected}, 'Archive contains files outside the reviewed desk closure')
    require(manifest['desk_sources'] == origins, 'Desk source provenance differs')
    license_pin = contract['kernel_files']['LICENSE.txt']
    require(digest(members['notices/urbit-kernel-LICENSE.txt']) == license_pin['sha256']
            and len(members['notices/urbit-kernel-LICENSE.txt']) == license_pin['bytes'], 'Kernel license differs')
    return frontend_raw


def verify_bytes(raw, *, expected_sha256, target):
    require(isinstance(expected_sha256, str) and re.fullmatch(r'[0-9a-f]{64}', expected_sha256), 'External trusted SHA-256 required')
    require(0 < len(raw) <= MAX_ARCHIVE and digest(raw) == expected_sha256, 'Archive digest/size differs')
    members = {}
    with tarfile.open(fileobj=io.BytesIO(raw), mode='r:') as archive:
        for item in archive:
            require(len(members) < MAX_MEMBERS and item.isfile() and not item.pax_headers
                    and 0 < item.size <= MAX_FILE, 'Unsafe archive member')
            require(item.name.startswith(PREFIX), 'Foreign archive root')
            name = item.name[len(PREFIX):]
            require(re.fullmatch(r'[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)*', name) and '..' not in name.split('/')
                    and name not in members, 'Unsafe or duplicate archive path')
            require((item.uid, item.gid, item.mtime, item.mode, item.uname, item.gname) == (0, 0, 0, 0o644, '', ''), 'Noncanonical archive metadata')
            members[name] = archive.extractfile(item).read(item.size + 1)
            require(len(members[name]) == item.size, 'Truncated archive member')
    require(canonical_archive(members) == raw, 'Noncanonical archive or trailing bytes')
    require('manifest.json' in members, 'Missing release manifest')
    manifest = json.loads(members['manifest.json'], object_pairs_hook=unique)
    require(isinstance(manifest, dict) and set(manifest) == {'protocol', 'kind', 'role', 'source_commit', 'packager_sha256', 'shared_packager_sha256',
                            'contract_sha256', 'toolchain_sha256', 'frontend_sha256', 'compatibility', 'saved_state_version',
                            'agents', 'docket', 'qualification', 'files', 'desk_sources'}, 'Release manifest shape')
    require(manifest['protocol'] == 'stead.release-package/1' and manifest['kind'] == 'offline-desk-candidate', 'Release protocol/kind')
    require(isinstance(manifest['source_commit'], str) and re.fullmatch(r'[0-9a-f]{40}', manifest['source_commit']), 'Release source identity')
    require(all(isinstance(manifest[name], str) and re.fullmatch(r'[0-9a-f]{64}', manifest[name])
                for name in ('packager_sha256', 'shared_packager_sha256', 'contract_sha256', 'toolchain_sha256', 'frontend_sha256')), 'Release digest identity')
    require(manifest['docket'] == 'not-included-native-route-candidate', 'Unverified docket metadata')
    require(isinstance(manifest['files'], dict) and set(manifest['files']) == set(members) - {'manifest.json'}, 'Manifest/member inventory differs')
    for name, pin in manifest['files'].items():
        validate_pin(pin)
        require(len(members[name]) == pin['bytes'] and digest(members[name]) == pin['sha256'], 'Release member digest differs')
    contract = json.loads(members['source/release-contract.json'], object_pairs_hook=unique)
    validate_contract(contract)
    require(digest(members['source/release-contract.json']) == manifest['contract_sha256']
            and digest(members['source/toolchain.lock.json']) == manifest['toolchain_sha256'] == contract['toolchain_sha256'], 'Release provenance digest differs')
    require(isinstance(manifest['role'], str) and manifest['role'] in contract['agents'] and manifest['agents'] == [contract['agents'][manifest['role']]]
            and type(manifest['saved_state_version']) is int
            and manifest['saved_state_version'] == contract['saved_state_versions'][manifest['role']], 'Release role/state differs')
    require(manifest['compatibility'] == {key: contract[key] for key in ('kernel_kelvin', 'kernel_commit', 'runtime_version', 'runtime_binary_sha256', 'api_version')}, 'Manifest compatibility differs')
    require(manifest['qualification'] == {'package_integrity_only': True, 'native_install': False, 'upgrade_recovery': False, 'canary': False, 'production': False}
            and all(type(value) is bool for value in manifest['qualification'].values()), 'Package cannot claim native/release qualification')
    require(isinstance(target, dict) and set(target) == TARGET_KEYS and target == target_profile(manifest)
            and all(type(target[key]) is int for key in ('kernel_kelvin', 'api_version', 'saved_state_version')), 'Target compatibility/frontend differs')
    require(members['desk/sys.kelvin'] == f"[%zuse {target['kernel_kelvin']}]\n".encode()
            and members['desk/desk.bill'] == f":~  %{manifest['agents'][0]}\n==\n".encode(), 'Desk compatibility/agents differ')
    frontend_raw = verify_closure(members, manifest, contract)
    require(frontend_raw == members['source/frontend.json'] and digest(frontend_raw) == manifest['frontend_sha256'], 'Frontend release binding differs')
    return manifest


def write_new(root, output, raw):
    with held_parent(root, output) as (parent, leaf, check_binding):
        descriptor = os.open(leaf, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600, dir_fd=parent)
        with os.fdopen(descriptor, 'wb') as stream:
            stream.write(raw)
        check_binding()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='operation', required=True)
    build = sub.add_parser('build')
    build.add_argument('--role', choices=['home', 'identity'], required=True)
    build.add_argument('--source', default='HEAD')
    build.add_argument('--output', required=True, help='New checkout-relative archive; existing parent required')
    verify = sub.add_parser('verify')
    verify.add_argument('--archive', required=True)
    verify.add_argument('--sha256', required=True, help='Digest obtained from a separately trusted release record')
    verify.add_argument('--target', required=True, help='Checkout-relative JSON declaring the intended runtime/state/frontend profile')
    args = parser.parse_args()
    try:
        if args.operation == 'build':
            raw, manifest = archive_bytes(role=args.role, reference=args.source)
            write_new(ROOT, args.output, raw)
        else:
            raw = read_bounded(ROOT, args.archive, MAX_ARCHIVE)
            target = json.loads(read_bounded(ROOT, args.target, 8192), object_pairs_hook=unique)
            manifest = verify_bytes(raw, expected_sha256=args.sha256, target=target)
        print(json.dumps({'classification': 'offline-package-integrity-only', 'operation': args.operation,
                          'sha256': digest(raw), 'bytes': len(raw), 'source_commit': manifest['source_commit'],
                          'target_profile': target_profile(manifest), 'native_execution': False, 'qualification': False}, sort_keys=True))
    except (ValueError, OSError, KeyError, TypeError, UnicodeError, tarfile.TarError, subprocess.SubprocessError) as error:
        parser.exit(1, 'Release candidate failed: ' + str(error) + '\n')


if __name__ == '__main__':
    main()
